import type { CommodityCategory, Currency } from "@/lib/types";

/* ============================================================
   Definisi dasar komoditas yang dipantau di halaman Harga.

   PENTING: angka `basePrice` di bawah adalah nilai acuan SIMULASI yang
   dipakai sebagai titik awal pergerakan harga. Ini BUKAN kutipan pasar
   sungguhan. Untuk harga resmi, gunakan sumber di kolom `source`.
   ============================================================ */

export interface CommodityDef {
  id: string;
  name: string;
  category: CommodityCategory;
  /** Bursa atau lembaga acuan. */
  market: string;
  hsCode: string;
  basePrice: number;
  currency: Currency;
  /** Satuan harga yang ditampilkan apa adanya, mis. "USD/MT". */
  priceUnit: string;
  /** Volatilitas harian relatif (0,01 = 1%). Dipakai oleh mesin simulasi. */
  volatility: number;
  /** URL sumber resmi supaya pengguna bisa cek harga sebenarnya. */
  sourceUrl: string;
  sourceLabel: string;
}


/**
 * Turunkan daftar dokumen mutu dari kategori komoditas.
 *
 * Penawaran dan permintaan diperlakukan berbeda dengan sengaja:
 *  - supply : hanya dokumen inti, karena maknanya "yang bisa saya sediakan".
 *  - demand : daftar lebih lengkap, karena pembeli biasanya memerinci
 *             persyaratannya termasuk yang sifatnya nilai tambah.
 */
function seedQualityDocs(listing: SeedListing): QualityDocRequirement[] {
  return listing.kind === "supply"
    ? defaultQualityDocs(listing.category)
    : suggestQualityDocs(listing.category);
}

/** Gabungan seluruh data contoh, diurutkan dari yang terbaru. */
export const SEED_LISTINGS: Listing[] = [...SUPPLY, ...DEMAND]
  .map((listing) => ({
    ...listing,
    qualityDocuments: seedQualityDocs(listing),
  }))
  .sort(
    (a, b) => new Date(b.createdAt).getTime() - new Date(a.createdAt).getTime(),
  );

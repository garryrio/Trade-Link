const DAY_MS = 86_400_000;

/**
 * Buat timestamp `n` hari lalu, dipaku pada jam tertentu (WIB) supaya
 * nilainya stabil. Dievaluasi di server saat modul dimuat.
 */
function daysAgo(days: number, hourWIB = 10): string {
  const d = new Date(Date.now() - days * DAY_MS);
  // WIB = UTC+7, jadi jam WIB dikurangi 7 untuk mendapat jam UTC.
  d.setUTCHours(hourWIB - 7, 0, 0, 0);
  return d.toISOString();
}

/** Buat tanggal `n` hari ke depan (untuk deadline permintaan). */
function daysAhead(days: number): string {
  const d = new Date(Date.now() + days * DAY_MS);
  d.setUTCHours(16, 0, 0, 0);
  return d.toISOString();
}

